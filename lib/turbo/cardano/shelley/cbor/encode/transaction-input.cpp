#include <turbo/cardano/shelley/block.hpp>

namespace turbo::cardano::shelley {
    void transaction_input_t::to_cbor(era_encoder &enc) const
    {
        enc.array(2).bytes(value.hash).uint(static_cast<size_t>(value.idx));
    }
}
